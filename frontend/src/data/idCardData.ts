export function lookupIdCard(code: string): { province: string; city: string; district: string } | null {
  if (code.length < 6) return null;
  const regionCode = code.slice(0, 6);
  for (const [rc, province, city, district] of idCardRegions) {
    if (regionCode === rc) return { province, city, district };
  }
  // 模糊查找（只匹配前4位地市码）
  const pre4 = regionCode.slice(0, 4);
  for (const [rc, province, city, district] of idCardRegions) {
    if (pre4 === rc.slice(0, 4)) return { province, city, district };
  }
  // 模糊查找省码
  const pre2 = regionCode.slice(0, 2);
  const provinceMap: Record<string, string> = {
    '11':'北京','12':'天津','13':'河北','14':'山西','15':'内蒙古',
    '21':'辽宁','22':'吉林','23':'黑龙江',
    '31':'上海','32':'江苏','33':'浙江','34':'安徽','35':'福建','36':'江西','37':'山东',
    '41':'河南','42':'湖北','43':'湖南','44':'广东','45':'广西','46':'海南',
    '50':'重庆','51':'四川','52':'贵州','53':'云南','54':'西藏',
    '61':'陕西','62':'甘肃','63':'青海','64':'宁夏','65':'新疆',
    '71':'台湾','81':'香港','82':'澳门',
  };
  if (provinceMap[pre2]) return { province: provinceMap[pre2], city: '未知', district: '未知' };
  return null;
}

// 身份证校验
export function validateIdCard(id: string): { valid: boolean; message: string } {
  const cleaned = id.trim().toUpperCase();
  // 长度
  if (!/^\d{17}[\dX]$/.test(cleaned)) {
    if (/^\d{15}$/.test(cleaned)) return { valid: true, message: '15位旧版身份证' };
    return { valid: false, message: '身份证号码应为18位数字，末位可为X' };
  }
  // 校验码
  const weights = [7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2];
  const checkCodes = ['1','0','X','9','8','7','6','5','4','3','2'];
  let sum = 0;
  for (let i = 0; i < 17; i++) sum += parseInt(cleaned[i]) * weights[i];
  const expected = checkCodes[sum % 11];
  if (cleaned[17] !== expected) return { valid: false, message: '校验码不通过，末位应为 ' + expected };
  // 日期
  const year = parseInt(cleaned.slice(6, 10));
  const month = parseInt(cleaned.slice(10, 12));
  const day = parseInt(cleaned.slice(12, 14));
  if (month < 1 || month > 12 || day < 1 || day > 31) return { valid: false, message: '出生日期无效' };
  const date = new Date(year, month - 1, day);
  if (date.getFullYear() !== year || date.getMonth() + 1 !== month || date.getDate() !== day) return { valid: false, message: '出生日期无效' };
  return { valid: true, message: '校验通过' };
}
