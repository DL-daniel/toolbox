export function searchWubi(char: string): [string, string][] | null {
  const results = wubiData.filter(([c]) => c === char);
  return results.length > 0 ? results.map(([_, code, explain]) => [code, explain]) : null;
}

export function searchByCode(code: string): string[] {
  return wubiData.filter(([_, c]) => c.startsWith(code.toUpperCase())).map(([char]) => char);
}
